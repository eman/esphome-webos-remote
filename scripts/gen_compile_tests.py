"""Writes tests/compile/*.yaml: the examples, with the GitHub package import replaced by local !includes of this
checkout, for each chip in MATRIX. Run from the repository root; CI fails if the output differs."""

import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BOARDS = {"esp32c6": "esp32-c6-devkitc-1", "esp32s3": "esp32-s3-devkitc-1", "esp32": "esp32dev"}
MATRIX = [
    ("ir-only", "esp32c6"),
    ("ir-only", "esp32"),
    ("bluetooth-only", "esp32c6"),
    ("bluetooth-ir", "esp32c6"),
    ("bluetooth-ir", "esp32s3"),
    ("capture", "esp32c6"),
]


def convert(text, variant):
    files = re.findall(r"^      - (packages/\S+)$", text, flags=re.M)
    start = text.index("packages:\n")
    end = text.find("\n\n", start)
    rest = text[end:] if end >= 0 else "\n"
    pin = "  ir_tx_pin: GPIO4\n" if variant == "esp32" else ""  # GPIO7 is a flash pin on the original ESP32
    local = "substitutions:\n  webos_remote_source: ../../components\n" + pin + "\npackages:\n" + "".join(
        f"  {os.path.splitext(os.path.basename(f))[0]}: !include ../../{f}\n" for f in files
    )
    text = text[:start] + local + rest.lstrip("\n").join(["\n", ""]) if rest.strip() else text[:start] + local
    text = re.sub(r"  board: \S+\n  variant: \S+\n", f"  board: {BOARDS[variant]}\n  variant: {variant}\n", text)
    return re.sub(r"^  name: (\S+)$", rf"  name: \1-{variant}", text, count=1, flags=re.M)


def main():
    out = os.path.join(ROOT, "tests", "compile")
    for example, variant in MATRIX:
        with open(os.path.join(ROOT, "examples", f"{example}.yaml")) as f:
            text = convert(f.read(), variant)
        with open(os.path.join(out, f"{example}-{variant}.yaml"), "w") as f:
            f.write(f"# Generated by scripts/gen_compile_tests.py from examples/{example}.yaml.\n" + text)


if __name__ == "__main__":
    main()
